/** 基础帧数据只作默认值；每名可玩角色都拥有完整的九方向角色专属招式表。 */
const ATTACK_DIRS = [
  'neutral', 'forward', 'back', 'up', 'upForward', 'upBack', 'down', 'downForward', 'downBack',
] as const

const MOVE_STYLE: Record<string, { startup: number; damage: number; recovery: number; reach: number }> = {
  li: { startup: 0, damage: 1, recovery: 1, reach: 0 },
  aoi: { startup: -1, damage: -2, recovery: -2, reach: 2 },
  ken: { startup: 1, damage: 3, recovery: 3, reach: -2 },
}

const MOVE_NAMES: Record<string, Record<(typeof ATTACK_DIRS)[number], string>> = {
  li: { neutral: '磨刀快斩', forward: '踏步重斩', back: '回身反切', up: '挑灯斩', upForward: '跃步斜斩', upBack: '回身挑斩', down: '扫堂斩', downForward: '贴地突刺', downBack: '退步扫斩' },
  aoi: { neutral: '灯芯点刺', forward: '疾风箭步', back: '燕返踢', up: '挑灯踢', upForward: '跃灯踢', upBack: '回身踢', down: '滑步扫踢', downForward: '俯身突袭', downBack: '撤步反踢' },
  ken: { neutral: '铁拳', forward: '重装冲拳', back: '铁肘回击', up: '擎天拳', upForward: '破阵上勾', upBack: '回身铁肘', down: '震地重踏', downForward: '铁掌突进', downBack: '撤步横扫' },
}

for (const char of CHARS) {
  if (char.locked) continue
  const style = MOVE_STYLE[char.id] ?? MOVE_STYLE.li!
  char.moves = Object.fromEntries(ATTACK_DIRS.map((dir) => {
    const variance = dir === 'forward' || dir === 'down' ? 1 : dir === 'neutral' ? 0 : -1
    return [dir, {
      name: MOVE_NAMES[char.id]?.[dir],
      startup: Math.max(2, 5 + style.startup + variance),
      active: 4 + (dir === 'down' || dir === 'downForward' ? 1 : 0),
      recovery: Math.max(5, 12 + style.recovery - variance),
      damage: Math.max(4, 10 + style.damage + (dir === 'forward' ? 3 : dir === 'down' ? 2 : 0)),
      fwd: Math.max(8, 30 + style.reach + (dir.includes('Forward') ? 8 : 0)),
      boxW: dir.includes('up') ? 38 : 46,
      boxH: dir.includes('up') ? 48 : 30,
      angle: dir.includes('up') ? 78 : dir === 'down' ? -60 : dir === 'back' || dir === 'downBack' ? 135 : 42,
      kbGrowth: char.id === 'ken' ? 1.2 : char.id === 'aoi' ? 0.92 : 1.04,
      baseKB: char.id === 'ken' ? 38 : char.id === 'aoi' ? 25 : 31,
    }]
  })) as CharDef['moves']
}

let activeChars: CharDef[] = CHARS

export function setCharacterCatalog(chars: CharDef[]): void {
  if (chars.length > 0) activeChars = chars.map((char) => ({ ...char, moves: char.moves ?? CHARS.find((fallback) => fallback.id === char.id)?.moves }))
}

export function charById(id: string): CharDef | undefined {
  return activeChars.find((c) => c.id === id) ?? CHARS.find((c) => c.id === id)
}

export function characterCatalog(): CharDef[] {
  return activeChars
}

